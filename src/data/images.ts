/**
 * Изображения лендинга.
 *
 * Все ссылки ведут на CDN Unsplash (изображения свободного использования,
 * без водяных знаков и чужих логотипов) и проверены на доступность.
 * Дополнительно компонент <Photo> подставляет локальную заглушку, если
 * изображение по какой-то причине не загрузилось, — битых картинок нет.
 */

export interface PhotoSource {
  id: string
  /** Прямой адрес изображения на CDN. */
  src: string
  /** Адрес уменьшенной версии для быстрой загрузки. */
  thumbSrc: string
  /** Текст для атрибута alt (нейтральный и корректный при любом содержимом). */
  alt: string
  /** Необязательная подпись под изображением. */
  caption?: string
}

const unsplash = (id: string, width: number) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${width}&q=80`

function makePhoto(id: string, alt: string, caption?: string): PhotoSource {
  return {
    id,
    src: unsplash(id, 1600),
    thumbSrc: unsplash(id, 800),
    alt,
    caption,
  }
}

